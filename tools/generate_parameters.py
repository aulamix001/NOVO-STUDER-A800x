#!/usr/bin/env python3
"""Generate APVTS declarations from the sole versioned parameter contract."""
import json
from pathlib import Path
r=Path(__file__).resolve().parents[1]
m=json.loads((r/'config/parameters.v1.json').read_text())
presets=json.loads((r/'presets/factory.json').read_text())['presets']
q=lambda s:json.dumps(str(s),ensure_ascii=True)
a=['// Generated by tools/generate_parameters.py; do not hand-edit.','inline juce::AudioProcessorValueTreeState::ParameterLayout makeLayout() {','juce::AudioProcessorValueTreeState::ParameterLayout l;']
for p in m['parameters']:
 id=p['id']; label=(('L ' if id.startswith('ch1_') else 'R ') if id.startswith(('ch1_','ch2_')) else '')+p['label']

 head=f'juce::ParameterID{{{q(id)},1}}, {q(label)}'
 if p['type']=='choice':
  options=', '.join(q(x) for x in p['values']); default=p['values'].index(p['default'])
  a.append(f'l.add(std::make_unique<juce::AudioParameterChoice>({head},juce::StringArray{{{options}}},{default}));')
 elif p['type']=='bool':a.append(f'l.add(std::make_unique<juce::AudioParameterBool>({head},{str(p["default"]).lower()}));')
 else:
  ref=p.get('range_ref',''); lo=f'-float(a800::{ref})';hi=f'float(a800::{ref})'
  if 'range' in p:lo=str(float(p['range'][0]))+'f';hi=str(float(p['range'][1]))+'f'
  if ref=='kAlignmentRangeDbfs':lo='float(a800::kAlignmentRangeDbfs[0])';hi='float(a800::kAlignmentRangeDbfs[1])'
  a.append(f'l.add(std::make_unique<juce::AudioParameterFloat>({head},juce::NormalisableRange<float>({lo},{hi},0.01f),{float(p["default"])}f));')
a+=['return l;','}']
a+=[f'struct FactoryPreset {{ const char* name; std::array<float,{len(m["parameters"])}> values; }};','inline const std::array<FactoryPreset,90> factoryPresets{{']
for pr in presets:
 vals=[]
 for p in m['parameters']:
  val=pr['parameters'][p['id']]
  if p['type']=='choice':val=p['values'].index(val)
  vals.append(str(float(val))+'f')
 a.append('FactoryPreset{'+q(pr['name'])+', {{'+','.join(vals)+'}}},')
a+=['}};',f'inline constexpr std::array<const char*,{len(m["parameters"])}> parameterIds{{{{'+','.join(q(p['id']) for p in m['parameters'])+'}};']
(r/'src/GeneratedParameters.h').write_text('\n'.join(a)+'\n')
print('APVTS layout + 90 host programs generated')
